/**
 * 卡片公开 API 工具（2026-10-11）的模型可见说明。
 *
 * 「卡片」= web 前端里在浏览器内运行的一帧界面（项目预览页、外置卡），每张卡对外暴露一组
 * 公开命令（统一标准集 + 卡片自定义）。本工具是 agent 侧的唯一入口：列卡（list）与驱动卡（call）。
 * 后端链路：card_call → 网关 POST /gateway/card-call → 选**持卡的那台浏览器** → WS 下行 →
 * 前端总线 cardBus 转译 → 卡片执行并回 ack → 原路带回。卡片侧对本链路无感（零改动）。
 *
 * prompt 里必须写清、否则模型必然用错的三件事：
 *   ①「在场」是硬前提——卡没在浏览器里打开就调不到，且 agent **不能**打开它（那是用户手势）；
 *   ② 寻址三字段的优先级与用途（instanceId 精确定位卡，label 定位项目归属，ns 跨设备选浏览器）；
 *   ③ 各类失败（无浏览器 / 卡不在场 / 超时）是链路问题不是命令问题，重试无益。
 */

export const CARD_CALL_DESCRIPTION = '列浏览器里在场的卡片，或调用某张卡的公开命令（驱动 web 界面卡片）'

export function getCardCallPrompt(): string {
  return `驱动浏览器里**在场卡片**的公开 API。卡片 = web 前端里正在运行的一帧界面（项目预览页、外置卡），每张卡对外暴露一组公开命令。

## 两个动作

- **\`action:'list'\`** —— 列出当前在场卡片（instanceId、归属 label、命名空间 ns、**它申报的命令名**、就绪状态）。**先 list 再 call**：命令名由卡片自己申报，不 list 就猜不到。
- **\`action:'call'\`** —— 调一张卡的一条命令，须给 \`cmd\`；\`args\` 是命令参数（原样平铺进命令信封）。

## 寻址（call 至少给一个）

- \`instanceId\`（最精确，取自 list）—— 直接锁定某一张卡。
- \`label\` —— 卡所属项目 label（与 \`/gateway/sessions\` 的 label 同口径），用于按项目定位。
- \`ns\` —— 卡片命名空间（如 \`floria-pv\`）。**ns 用于跨设备选「持卡的那台浏览器」**；同一浏览器内多卡并存时，卡内定位仍靠 instanceId / label。

## 命令契约

- **标准方法集**：\`state\`（探活兼快照——返回卡内当前状态；卡必须实现）、\`open\`（可选——打开一个资源，参数 \`path\` = **项目根相对 POSIX 路径**）。其余命令都是卡片自定义的，名字与参数**一律以 list 申报为准**。
- 命令**无状态、幂等优先**；每条命令恒回一条回执，成败都在回执里（失败带原因，不静默）。
- 长动作由卡片自己等完再回执，本工具只做超时兜底（\`timeoutMs\`，500..60000，默认 8000）。

## 失败语义（多为链路问题，重试无益）

- **无浏览器在线**：当前没有 web 前端连着网关 → 没有卡可调。
- **目标卡不在场**：浏览器在线但没有匹配的卡（多半是用户没打开对应项目预览 / 卡片）——回执会附**当场能力表**，据此改寻址或先 list。**agent 不能打开或启动一张卡**（那是用户手势）。
- **卡超时 / 设备中途断开**：命令发出后卡片未在时限内回执，或持卡浏览器掉线。

## 调用约束（硬性）

- **只在任务确实需要读/驱动浏览器界面里的卡片状态时才调**；能靠文件系统或现有上下文解决的，一律自己解决。
- **禁止礼节性/探测性调用**（"在吗"、已知没卡也去试探）。
- 卡片命令是**对外可见的动作**（可能改变用户屏幕内容），只在用户意图需要时执行；不确定就先 list 看清有什么。`
}
